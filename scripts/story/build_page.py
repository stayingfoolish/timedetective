def src_link(key):
    name, url, _ = SRC[key]
    return f'<a href="{esc(url)}">{esc(name)}</a>'


def rail(now=None, links=False, stop_after=None):
    items = []
    for i, n in enumerate(NODES, 1):
        if stop_after and i > stop_after:
            break
        cls = "now" if i == now else "done" if now and i < now else ""
        items.append(f'<li class="{cls}">' + (f'<a href="#q{i}">{i} {n}</a>' if links else f"{i} {n}") + "</li>")
        if stop_after == i:
            items.append('<li class="stop">refused</li>')
    if not stop_after:
        items.append('<li class="end">finding</li>')
    label = "The six steps of the playbook" if links else (f"Step {now} of {len(NODES)}" if not stop_after else f"Stopped at step {stop_after}")
    return f'<ol class="rail" aria-label="{label}">' + "".join(items) + "</ol>"


