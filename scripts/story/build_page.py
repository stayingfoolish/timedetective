def mag(x, d=1): return f"{abs(x):.{d}f}"
def sgn(x, d=1): return ("−" if x < 0 else "+") + f"{abs(x):.{d}f}"
def pval(p): return f"{p:.3f}" if p < 0.01 else f"{p:.2f}"
def floor_to(x, s): return math.floor(x / s) * s
def ceil_to(x, s): return math.ceil(x / s) * s


def span(a, b, d=1):
    lo, hi = sorted((abs(a), abs(b)))
    return f"{lo:.{d}f} to {hi:.{d}f}"


