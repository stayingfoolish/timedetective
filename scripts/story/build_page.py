def md_step(step):
    p = D["procedures"]["storage_" + NODES[step - 1]]
    here, outcome = HERE_TEXT[step]
    return (f'**Step {step} of {len(NODES)}** · [`{p["name"]}`]({B["procedure_paths"][p["name"]]}) · rule from {md_src(p["source"])} · '
            f'{here.replace(" · ", ", ")} → **{outcome}**')


def checks_md():
    rows = ["| What the critic reads | North-west India | US High Plains |", "| --- | --- | --- |"]
    for label, india, plains in CHECKS:
        if india is None:
            rows.append(f"| *{label}* | | |")
        else:
            rows.append(f"| {label} | " + " | ".join(("✓ " if ok else "✗ ") + text for ok, text in (india, plains)) + " |")
    rows.append(f'| **Label** | **{IND["strength"]}** | **{HP["strength"]}** |')
    return "\n".join(rows)


def procedures_md():
    rows = ["| Step | Procedure | What it does | Rule from |", "| --- | --- | --- | --- |"]
    for i, n in enumerate(NODES, 1):
        p = D["procedures"]["storage_" + n]
        rows.append(f'| {i} | [`{p["name"]}`]({B["procedure_paths"][p["name"]]}) | {DESC[p["name"]]} | {md_src(p["source"])} |')
    return "\n".join(rows)


def fill(text, values):
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", str(v))
    left = sorted(set(re.findall(r"\{\{(\w+)\}\}", text)))
    assert not left, left
    return text


